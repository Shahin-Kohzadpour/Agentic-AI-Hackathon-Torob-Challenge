/** Customer-facing wording. Internal records retain their original provenance. */
export function customerText(value: string): string {
  if (/شبیه|سناریو|تماس واقعی/.test(value)) {
    if (/لغو/.test(value)) return "بررسی لغو شد؛ می‌توانید گزینهٔ دیگری را انتخاب کنید.";
    if (/کارت مراجعه/.test(value)) return "برنامهٔ مراجعه آماده شد. پیش از حرکت، قیمت، موجودی و ساعت مراجعه را از فروشگاه تأیید کنید.";
    if (/جایگزین|فروشگاه.*مناسب مراجعه نشد/.test(value)) return "گزینهٔ دیگری با حفظ شرایط خرید شما پیشنهاد شد؛ قیمت، فاصله و گارانتی را در کارت فروشگاه مقایسه کنید.";
    return "بررسی اولیه انجام شد. قیمت، موجودی و زمان مراجعه هنوز به تأیید فروشگاه نیاز دارند.";
  }
  return value
    .replace(/در این دیتاست/g, "در نتایج فعلی")
    .replace(/دیتاست ترب/g, "اطلاعات فروشگاه‌ها")
    .replace(/دیتاست/g, "اطلاعات ثبت‌شده")
    .replace(/کاتالوگ/g, "فهرست محصولات")
    .replace(/در داده ثبت نشده/g, "ثبت نشده")
    .replace(/در داده/g, "ثبت‌شده");
}
